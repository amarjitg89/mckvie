           Unnat Bharat Abhiyan is a Scheme by the Ministry of Education (MoE) conducted under the leadership of IIT, Delhi. MCKV Institute of Engineering is selected as a PI (Participating Institute) with Dr. Brojendranath Dey of Department of Basic Science, MCKVIE working as the UBA coordinator.</br></br>
           
           
           UBA’s vision is to bring transformational change in rural development processes by leveraging knowledge institutions to help build the architecture of an Inclusive India. The Mission of Unnat Bharat Abhiyan is to enable higher educational institutions to work with the people of rural India in identifying the challenges and provide appropriate solutions for accelerating sustainable growth. It also aims to create a virtuous cycle between society and an inclusive academic system by providing knowledge and practices for emerging professions and to upgrade the capabilities of both the public and the private sectors in responding to the developmental needs of rural India.</br></br>

MCKV Institute of Engineering has taken the responsibility of five villages from Purba Bardhaman district. Our institute aspires to providetechnically easy, sustainable end ecofriendly solutions to problems in these rural areas.</br></br>


An initial survey by Dr. Brojendranath Dey and Dr. Tanmoy Roy Chowdhury has revealed that one of the challenges in the area is of Solid Waste Management. Our institute has conducted an awareness programme on waste management covering three villages. The programme was organized by 1st year B.Tech Students with the objective to educate the local people on solid waste management and its impact on environment, especially plastics. In order to create maximum impact on the villagers and spread awareness, they performed street plays relevant to the above mentioned topic. MCKV Institute of Engineering invites voluntary participation from all students and staff members and requests everyone to contribute by providing solutions for building a better and developed rural India.</br></br>

