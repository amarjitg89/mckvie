MCKV Institute of Engineering organized an awareness and drawing competition Programme on 28th August 2022 at Jamalpur Ramkrishna Vivekananda Vidyalaya, Jamalpur-II Block. The programme was organised by Dr. Brojendranath Dey with the help of all teachers of Ramkrishna Vivekananda Vidyalaya, drawing teacher and local political leader (Upo-Pradhan). Objective of this programme was to sensitized of the students and aware local people on solid waste management, specially plastics and also discussed about some action plans and their implementation. This programme is found to be very effective and made good impression on our environment and society.  


                   
