              The Emerging Technology Lab – Electric Vehicle (EV) Laboratory at MCKV Institute of Engineering (MCKVIE) has been established in strategic collaboration with Ather Energy Limited, one of India's leading electric two-wheeler manufacturers. This Centre of Excellence is dedicated to nurturing future-ready engineers through industry-integrated education, advanced technical training, and innovation-driven learning.</br></br>
               
               The collaboration has been formalized through a Memorandum of Understanding (MoU), under which Ather Energy has donated two electric scooters to MCKVIE for research and hands-on practical training. In line with the Government of India's vision of sustainable transportation and green mobility, the laboratory serves as a Centre of Excellence for skill development, research, innovation, and academia-industry collaboration. It is designed to equip students, researchers, and professionals with the technical knowledge and practical competencies required to excel in the rapidly evolving electric vehicle ecosystem.</br></br>
               
               The laboratory offers comprehensive hands-on training in key domains, including Electric Vehicle Design and Development, EV Powertrain Systems, Electric Motors and Motor Controllers, Lithium-ion Battery Technology, Battery Management Systems (BMS), EV Charging Infrastructure, Power Electronics, Automotive Electronics, Vehicle Diagnostics, and EV Safety Practices. The facility also supports interdisciplinary research, product development, and technology-driven innovation in emerging areas of electric mobility.

                      
