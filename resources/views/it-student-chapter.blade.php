        <div class="red mainhome_title mb-3 text-start">About the  <span class="blue fw-normal">Chapter</span></div> 
        
        
        The Institution of Engineers (India), IE (India) is the national organisation for Engineers in India. It was founded in 1920 in Madras with Sir Thomas R.J. Ward as the founding President. It is the largest multi-disciplinary engineering professional society in the English-speaking World. The Institute of Engineers (India) Student Chapter in association with the Information Technology Department of MCKV Institute of Engineering aims to bridge the gap between academics and industry by organizing seminars, workshops, technical talks, industrial interactions, competitions, and professional development activities. The chapter encourages students to improve technical knowledge, innovation skills, research exposure, and industry readiness.</br></br>
            
         <div class="red mainhome_title mb-3 text-start">Objective of the   <span class="blue fw-normal">Chapter</span></div> 
         
         To build interaction between academia and industry professionals, enhance technical and professional skills, and prepare students for emerging technologies and real-world challenges.</br></br>
         
         
