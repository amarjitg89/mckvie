          Technotica is the in-house engineering & technology model development competition started in the year 2004. The event is held annually. Student from all the departments of the MCKVIE form teams, develop a model prototype and participate in this competition. The primary goals of this competition is to benefit the students beyond the syllabus in terms of:</br></br>
          
          <ul>
              <li>Domain and cross-domain familiarity and skill enhancement</li>
               <li>Development of project and defending their work in front of panel of judges and visitors
</li>
                <li>Understanding and learning operations by studying through a device manual
</li>
                 <li>Encoding a software module to bridge with a hardware(driver) to make it functional
</li>
                  <li>Encouraging the zeal and enthusiasm of young minds to let them unleash their creative thoughts
</li>
                   <li>Working in a team as a member or leader</li>
              
          </ul></br>
          
          
Nonetheless, this participation, eventually, helps the students in the job interviews they face during the 3rd/4th year campus drives where they can exhibit this as a real life project experience.</br></br>

At the first level, on announcement of Technotica, the students are required to form a team and then to submit an abstract as a brief write-up of their Project Plan. Afterwards, they need to present their proposal before the internal panel of judges where the first level selection is done.</br></br>

On the day of the competition each selected team presents their respective models allotted to their tables at the contest floor. They address the queries of the visitors by explaining their models. A group of external judges, invited from outside the Institute, visits every team and judge them on their merit by awarding marks and finally declare the result of the competition thereof. Models are evaluated on the basis of innovation, originality, practicability, understanding and presentation of work.  Apart from the first, second and third prizes, two more teams get the awards of special mention in the competition.</br></br>

As a follow-up of this competition, the awardees are encouraged to participate in contests organized outside the Institute. Every year winners of Technotica participate in Eastern India Science and Technology fair in BITM Kolkata and different other district level Science competitions. It’s an honour to mention here that, students regularly get rewarded in these events. 




                   
