      Institution’s Innovation Council (IIC) is an initiative of the Ministry of Education’s Innovation Cell (MIC) for fostering the culture of innovation amongst higher education Institutes. The Innovation Council was established to promote innovation in the Institution among the young students to work on new ideas and to familiarize them with concepts of improving products and services to the market, increasing efficiency and product profitability.</br></br>

The main aim of IIC is to conduct various activities related to innovation, entrepreneurship, IPR, and startups in collaboration with academicians, entrepreneurs, investors, and professionals for creating a mentor pool for student innovators. In order to achieve this aim, IIC holds motivational sessions, workshops to familiarize our students with the concept of ideation, innovation, start-ups and entrepreneurship. IIC members regularly organize and attend sessions on Entrepreneurship, Innovation as Career Opportunity, IPR and IP Management to make them familiar with the know-how to pitch new ideas and get funding. Such interactive sessions channelize the energy of young students and motivate them to work on new ideas, create start-ups and entrepreneurial ventures resulting in self-employment. The Innovation Council is always there to solve students’ creative problems and entrepreneurial mindset, therefore promoting strong intra-institutional and inter-institutional partnerships among the students and faculty members.</br></br>

Institution’s Innovation Council(IIC) is actively instrumental in providing opportunities to students and faculty to innovate and ideate through competitions like Idea Competition and Internal Software Hackathons. True to the spirit of MIC, the primary goal of IIC has been to empower minds and cultivate innovative ideas that can be useful to society. The opportunities provided by MIC have been extremely enriching in enabling the students and faculty to ensure organic growth in terms of innovation.</br></br>

