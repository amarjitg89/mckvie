            The MCKV Institute of Engineering (MCKVIE), in collaboration with the Institute of Indian Foundrymen (IIF), marked a significant milestone in industry-academic collaboration with the inauguration of its Students’ Chapter on <b>6th June 2025</b>. Organized in partnership with IIF-Eastern Region and IIF-Howrah Chapter, the event was held at the college campus in Liluah.</br></br>
            
            
            
   The objective of this student chapter is to bridge the classroom-industry gap in manufacturing by offering students hands-on practical training, expert lectures, and industry visits. Industry collaborations will be established under the Eastern Region and MCKVIE student chapter of the IIF to enhance student exposure to modern foundry technologies and best practices. Our students will be able to participate in regular industry visits, hands-on workshops, and major events like the Indian Foundry Congress. This initiative connects aspiring engineers with industry stalwarts and professionals to help them understand production, robotics, automation, and manufacturing processes.</br></br> 
   
   
