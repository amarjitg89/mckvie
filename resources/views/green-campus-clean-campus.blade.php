In accordance with the Green Campus Evaluation Plan, as suggested by the Internal Quality Assessment Cell (IQAC) of the college, The MCKV Institute of Engineering, Liluah, Howrah   is conducting a green audit of the college since AY 2016-2017.</br></br>

The purpose of the audit was to make sure that the practices followed in the campus are healthy and environment friendly. With this in mind, the specific objectives of the audit were to evaluate the degree to which the Departments are in compliance with the applicable regulations, policies and standards and to ensure that the development of the college aims at sustainable development and green campus.</br></br>

The methodology used included physical inspection of the campus and review of the relevant documentation.</br></br>


 <div class="blue mainhome_title mb-3 text-start fw-normal">  <span class="red fw-bold">Objective and </span>Scope </div>
 
 Although there is no universal definition of Green Audit, we may define it as systematic identification, quantification, recording, reporting and analysis   of   components   of   environmental   diversity.   The   “Green   Audit”   aims   to   analyze environmental practices within and outside (not in our purview) the college campus, which will have an impact on the eco-friendly ambience. It was initiated with the motive of inspecting the work conducted within the organizations whose exercises can cause risk to the health of inhabitants and the environment. Later on, it is implemented as a measure to enhance a healthy environment to almost all the organizations. Through Green Audit, one gets a direction as how to improve the condition of environment and there are various factors that have determined the growth of carrying out Green Audit. Green audit is assigned to the Criteria 7 of NAAC, National Assessment and Accreditation Council which is a self governing organization of India which declares the institutions as Grade A, B or C according to the scores assigned during the accreditation.</br></br>
 
 <span class="fs-6 fw-bolder  w-100 mb-3 d-flex blue">The main objectives of Green Audit are as follows :</span>
 
 <ul>
<li>To ensure development along with safeguarding the environment.</li>

<li>To reduce energy consumption to foster environment.</li>  

<li>To access weather the measures implemented by the MCKV Institute of Engineering, Liluah, Howrah have helped to reduce the Carbon Footprint.</li>  

<li>To assess whether investments made in increasing awareness among students regarding electricity, biodiversity and environment have helped the Institution achieve the required carbon dioxide emission and absorption in the campus.
</li>  

<li>To assess whether non-academic activities of the Institution support the collection, recovery, reuse and recycling of solid wastes that harm the environment.</li>  

<li>To identify gaps and suggest recommendations to improve the Green Campus status of the institution.</li>  
     
     
     
 </ul></br>
 
 
 The institute has an intention to adopt the ‘Green Campus‟ system for environmental conservation and sustainability. The goal is to reduce CO2 emission, energy and water usage, while creating an environmentally literate campus where students can learn the idea of protection of environment and stay healthy. The Green Campus‟ has been a very new concept adopted by this institute. The college administration is still working on the several facets of ‘Green Campus‟ including Water Conservation, Tree Plantation, Waste Management, Paperless Work, Carbon Footprints and Alternative Energy.</br></br>


 <div class="blue mainhome_title mb-3 text-start fw-normal">  <span class="red fw-bold">Audit Goals</span> of the Institute </div>
 
 The institute, with the advice of the Internal Quality Assessment Cell (IQAC) has set up an environmental quality assessment body (GREEN CAMPUS) that aimed at performing the green audit of the institution. The main objectives of the audit are :</br></br>
 
 <ul>
<li>More efficient resource management</li>

<li>To provide basis for improved sustainability</li> 

<li>To create a green campus</li> 

<li>To enable waste management through reduction of waste generation, solid- waste and water recycling</li> 

<li>Recognize the cost saving methods through waste minimizing and managing</li> 

<li>Point out the prevailing and forthcoming complications</li> 

<li>Impart environmental education through systematic environmental management approach and Benchmarking for environmental protection</li> 

<li>Financial savings through a reduction in resource use</li> 

<li>Enhancement of college profile</li> 
     
     
     
 </ul></br>

 <div class="blue mainhome_title mb-3 text-start fw-normal">  <span class="red fw-bold">Methodology</span> </div>
 
 The Green Audit taken up by the Green Audit team of The MCKV Institute of Engineering, Liluah, Howrah had been divided into three(3) stages :</br></br>


 
  <span class="fs-6 fw-bolder  w-100 mb-3 d-flex blue">I.  The Pre Audit Stage
</span>

In the pre-audit stage, meetings provide an opportunity to support the capacity and objectives of the audit and enable discussions on the feasibility associated with the audit. The meeting provides the first opportunity to meet the audit and deal with several practical knowledge and concerns. The meeting provided the chance to gather information that the audit team can study before arriving on the site. The audit procedure and audit plan was handed over at this meeting and discussed in advance of the audit itself. In The MCKV Institute of Engineering, Liluah, Howrah the planning of audit processes was discussed in the pre-audit meeting. Audit team was also selected in this meeting with the help of staff and the college management. The audit protocol and audit plan were handed over at this meeting and discussed in advance of the audit itself.</br></br>

The Management of the college has shown the commitment towards the green auditing during the pre-audit meeting. They were ready to encourage all green activities. It was decided to promote all activities that are environment friendly such as awareness programs on the environment, planting more trees on the campus, etc., after the green auditing. The management of the college was willing to formulate policies based on green auditing report.</br></br>

  <span class="fs-6 fw-bolder  w-100 mb-3 d-flex blue">II.  The Audit Stage :
</span>

The Audit Stage encompasses of the team selection and the field works performed. Looking after the unique structure, location and ambiance of the college, the Green Audit Team focused on Material Issues pertaining to college which have the highest influence on the Green Attributes of the College. The Audit stage also focused on the Methodology adopted. Checklist approach is adopted for transparent evaluation of the topics and increase readability for independent reader.</br></br>

  <span class="fs-6 fw-bolder  w-100 mb-3 d-flex blue">III.  The Post Audit Stage :</span>

The post-audit stage ensures formulation of Draft findings and sent to management response. Since the audit is done internally, it was important to ensure management approval for the draft. After getting draft approval, the audit team went for final report formulation.</br></br>

