           The Intel® Unnati Program, conceived by Intel India and launched in October 2021, is aligned with the National Education Policy 2020 and the Government’s efforts to propel India’s digital economy transformation. It aims to bridge the wide, and growing, skill gap between technical graduates and IT industry expectations, not just by developing new curricula and offering courses in emerging technologies, but also by promoting greater industry-academic linkages and focusing on research and innovation. 
</br></br>
             
Intel® Unnati Data-Centric Lab – Artificial Intelligence Lab has been deployed with server specification <b>3rd Generation Intel Xeon 5320-Gold 2.2 GHz Scalable Processors, Turbo 3.4GHz, (Total 52 core,104 Threads), NVIDIA Quadro RTXA6000 48GB DDR6 384BIT GPU (10752 CUDA Cores)</b>.</br></br>

Equipped with cutting-edge tools and resources, the lab aims to provide hands-on experience in emerging technologies such as Artificial Intelligence, Machine Learning, Neural Network, Deep Learning, Large Language Model, Advanced Data Analytics and Generative AI.</br></br>

As a part of Intel® Unnati Program, Intel® Unnati 5-Day Faculty Development Program (Train-the-Trainer Program) on “Working on Servers & Systems, Machine Learning & Deep Learning” was conducted from 15/07/2025 to 19/07/2025 at Intel® Unnati Data-Centric Lab in Emerging Technologies - Artificial Intelligence Lab, MCKV Institute of Engineering Campus. Suhaas D, Artificial Intelligence Engineer, EDGATE TECHNOLOGY PVD. LTD, Bangalore was the trainer for all the sessions of FDP. The FDP was coordinated by Dr. Deep Suman Dev, SPoC of Intel® Unnati Program for MCKVIE and organized for faculties of different departments of MCKVIE. The FDP aims to give Hands-on exposure in finding solutions for different real-time problems using Machine Learning and Deep Learning algorithms.




                      
